import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const entries=read('data/static/racecourses-public-timetable-identities-v1.json');
const locations=read('data/static/racecourse-locations-v1.json');
const evidence=read('data/static/racecourse-location-supplement-evidence-v1.json');
const id='cromwell-racecourse';
const venue=entries.filter(x=>x.id===id);
assert.equal(venue.length,1,'One Cromwell physical venue, not club/meet duplicate');
assert.equal(venue[0].country_id,'new-zealand');
assert.equal(venue[0].timezone,'Pacific/Auckland');
assert.deepEqual([...venue[0].racing_types].sort(),['harness','thoroughbred-flat'].sort());
assert.ok(venue[0].official_links.some(x=>x.url==='https://loveracing.nz/RaceInfo/Clubs-And-Courses/8/Racecourse.aspx'));
const points=locations.locations.filter(x=>x.id===id);
assert.equal(points.length,1);
const p=points[0].location;
assert.equal(p.latitude,-45.0424);
assert.equal(p.longitude,169.1676);
assert.equal(p.precision,'venue_approximate','Reserve location is NOT a surveyed racing oval center');
assert.equal(p.verification_state,'reviewed');
assert.equal(p.evidence.value,'data/static/racecourse-location-supplement-evidence-v1.json#'+id);
const e=evidence.entries.filter(x=>x.id===id);
assert.equal(e.length,1);
assert.match(e[0].coordinate_method,/NOT the adjacent NZCS aerodrome/);
assert.match(e[0].precision_note,/not independently surveyed/);
console.log('CROMWELL_PHYSICAL_VENUE_AND_MAP_EVIDENCE: pass');
