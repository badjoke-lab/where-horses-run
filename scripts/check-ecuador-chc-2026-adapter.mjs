import assert from 'node:assert/strict';
import {parseChcEcuador2026,buildChcEcuadorCMeeting,ECU_CHC_VENUE,ECU_CHC_SYSTEM} from './timetable/ecuador-chc-2026-core.mjs';
const dates=[['Jul.',5],['Jul.',26],['Ago.',9],['Ago.',30],['Sep.',20],['Sep.',27],['Oct.',11],['Oct.',18],['Nov.',8],['Dic.',27]];
const pages=Array.from({length:5},(_,i)=>i===0?['CALENDARIO CLÁSICO 2026','CONFEDERACIÓN HÍPICA DEL CARIBE']:[]);
for(let i=0;i<dates.length;i++)pages[Math.floor(i/3)+1].push('ECU','Miguel Salem D.',String(dates[i][1]),dates[i][0],'CLASICO NOMBRE NO PUBLICAR');
const rows=parseChcEcuador2026(pages);
assert.equal(rows.length,10);
assert.deepEqual(rows.filter(x=>x.date>='2026-10-20').map(x=>x.date),['2026-11-08','2026-12-27']);
assert.equal(new Set(rows.map(x=>x.date)).size,10);
assert.ok(rows.every(x=>x.racecourse_id===ECU_CHC_VENUE));
const meeting=buildChcEcuadorCMeeting(rows.at(-2),{checkedAt:'2026-10-20T00:00:00Z'});
assert.equal(meeting.capability_rank,'C');
assert.equal(meeting.racing_system_id,ECU_CHC_SYSTEM);
assert.equal(meeting.first_race_time_local,null);
assert.deepEqual(meeting.timetable_rows,[]);
assert.throws(()=>parseChcEcuador2026(pages.map(x=>x.filter(t=>t!=='ECU'))),/denominator/);
const altered=structuredClone(pages);
const p=altered.find(x=>x.includes('Nov.'));p[p.indexOf('Nov.')]='Oct.';
assert.throws(()=>parseChcEcuador2026(altered),/denominator|duplicate/);
