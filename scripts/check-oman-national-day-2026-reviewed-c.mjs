import assert from 'node:assert/strict';
import fs from 'node:fs';
import {OMAN_REVIEW,verifyManualEvidence,buildC} from './timetable/oman-national-day-2026-reviewed-c-core.mjs';
const e=JSON.parse(fs.readFileSync('data/static/calendar-reviewed-oman-national-day-2026.json','utf8'));
assert.deepEqual(verifyManualEvidence(e),['2026-11-21']);
assert.throws(()=>verifyManualEvidence({...e,date:'2026-11-22'}));
assert.throws(()=>verifyManualEvidence({...e,racecourse_id:'oman--other'}));
assert.throws(()=>verifyManualEvidence({...e,source_content_retained:true}));
assert.throws(()=>verifyManualEvidence({...e,rights_review:{...e.rights_review,automation_allowed:true}}));
assert.equal(e.rights_review.status,'USABLE_WITH_CONDITIONS');
assert.equal(e.rights_review.evidence_level,'E2');
const r=buildC('2026-11-21',{checkedAt:'2026-11-21T00:00:00Z'});
assert.equal(r.capability_rank,'C');
assert.equal(r.racecourse_id,'al-rahba-racecourse');
assert.equal(r.date,'2026-11-21');
assert.equal(r.first_race_time_local,null);
assert.equal(r.last_race_time_local,null);
assert.deepEqual(r.timetable_rows,[]);
assert.throws(()=>buildC('2026-12-18',{checkedAt:'2026-11-21T00:00:00Z'}),/Unreviewed/);
assert.throws(()=>buildC('2027-11-21',{checkedAt:'2026-11-21T00:00:00Z'}),/Unreviewed/);
console.log('OMAN_NATIONAL_DAY_C_REVIEWED_CONTRACT_PASS one meeting, one named physical track; no network');
